var updateGolden = flag.Bool("update", false, "rewrite testdata/*.golden.ts from generator output")

func loadSchema(t *testing.T, file string) Schema {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join("testdata", file))
	if err != nil {
		t.Fatalf("read fixture %s: %v", file, err)
	}
	schema, err := parseSchema(raw)
	if err != nil {
		t.Fatalf("parse fixture %s: %v", file, err)
	}
	return schema
}

func loadSchemas(t *testing.T, files ...string) []Schema {
	t.Helper()
	schemas := make([]Schema, 0, len(files))
	for _, f := range files {
		schemas = append(schemas, loadSchema(t, f))
	}
	return schemas
}

// --- GenerateTypeScript() ---

func TestGenerateTypeScript(t *testing.T) {
	tests := []struct {
		name     string
		fixtures []string
		golden   string
		contains []string
		absent   []string
	}{
		{
			name:     "record form article",
			fixtures: []string{"schema_article.json", "schema_category.json"},
			golden:   "article.golden.ts",
			contains: []string{
				"export interface ArticleDocument extends BaseDocument {",
				"  _type: 'article'",
				"  title: string",
				"  slug: string",
				"  excerpt?: string",
				"  category?: Reference<'category'> | CategoryDocument",
				"  content: RichTextValue",
				"  featured?: boolean",
				"  publishedAt?: string",
				"export interface CategoryDocument extends BaseDocument {",
				"  order?: number",
				" * Blog articles with rich content and metadata",
			},
		},
		{
			name:     "legacy array form",
			fixtures: []string{"schema_home_page.json", "schema_category.json"},
			golden:   "legacy.golden.ts",
			contains: []string{
				"export interface HomePageHeroCta {",
				"export interface HomePageHero {",
				"export interface HomePageBlocksItem {",
				"export interface HomePageDocument extends BaseDocument {",
				"  _type: 'home-page'",
				"  hero: HomePageHero",
				"  cta?: HomePageHeroCta",
				"  tags?: string[]",
				"  blocks?: HomePageBlocksItem[]",
				"  gallery?: unknown[]",
				"  cover?: MediaFieldValue | null",
				"  'hero-image'?: MediaFieldValue | null",
				"  related?: Reference<'category' | 'author'> | CategoryDocument",
				"  legacyOwner?: Reference<'author'>",
				"  weird?: unknown",
			},
			absent: []string{
				"AuthorDocument",
			},
		},
		{
			name:     "singleton",
			fixtures: []string{"schema_settings.json"},
			golden:   "singleton.golden.ts",
			contains: []string{
				" * Type: singleton",
				"export interface SiteSettingsDocument extends BaseDocument {",
				"  _type: 'siteSettings'",
				"  siteTitle: string",
				"  logo?: MediaFieldValue | null",
				"  maintenance?: boolean",
				"  theme?: unknown",
				"  launchedAt?: string",
				"export type DocumentType = 'siteSettings'",
				"  'siteSettings': SiteSettingsDocument",
			},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			out := GenerateTypeScript(loadSchemas(t, tt.fixtures...))

			// Shared preamble is always present and self-contained.
			for _, want := range []string{
				"// Generated by trokky CLI",
				"export interface BaseDocument {",
				"  _id: string",
				"  _status?: 'draft' | 'published'",
				"export interface MediaAssetReference {",
				"export interface MediaFieldValue {",
				"export interface Reference<T extends string = string> {",
				"export interface DocumentTypeMap {",
				"export type DocumentOf<T extends DocumentType> = DocumentTypeMap[T]",
			} {
				if !strings.Contains(out, want) {
					t.Errorf("output missing %q", want)
				}
			}
			if strings.Contains(out, "import ") {
				t.Error("output must not import anything")
			}

			for _, want := range tt.contains {
				if !strings.Contains(out, want+"\n") {
					t.Errorf("output missing line %q", want)
				}
			}
			for _, unwanted := range tt.absent {
				if strings.Contains(out, unwanted) {
					t.Errorf("output unexpectedly contains %q", unwanted)
				}
			}

			// DocumentTypeMap has one entry per collection.
			for _, s := range loadSchemas(t, tt.fixtures...) {
				entry := "  '" + s.Name + "': " + pascalCase(s.Name) + "Document\n"
				if !strings.Contains(out, entry) {
					t.Errorf("DocumentTypeMap missing entry %q", strings.TrimSpace(entry))
				}
			}

			goldenPath := filepath.Join("testdata", tt.golden)
			if *updateGolden {
				if err := os.WriteFile(goldenPath, []byte(out), 0644); err != nil {
					t.Fatalf("write golden: %v", err)
				}
				return
			}
			want, err := os.ReadFile(goldenPath)
			if err != nil {
				t.Fatalf("read golden (run with -update to create): %v", err)
			}
			if string(want) != out {
				t.Errorf("output does not match %s\n--- got ---\n%s", tt.golden, out)
			}
		})
	}
}

