func TestPascalCase(t *testing.T) {
	cases := map[string]string{
		"article":     "Article",
		"home-page":   "HomePage",
		"blogPost":    "BlogPost",
		"site_config": "SiteConfig",
		"page2":       "Page2",
		"2cool":       "_2cool",
		"":            "Unnamed",
	}
	for in, want := range cases {
		if got := pascalCase(in); got != want {
			t.Errorf("pascalCase(%q) = %q, want %q", in, got, want)
		}
	}
}

